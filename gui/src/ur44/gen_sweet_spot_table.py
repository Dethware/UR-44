#!/usr/bin/env python3
"""Generate SweetSpotTable.cpp: the built-in Sweet Spot Data presets as constant C++ data (run by the build).

Input: tools/ur44_sweet_spot.py (generated by re/extract_sweet_spot.py from the .ssd files in TOOLS for UR44)
  NOTICE    the copyright notice the presets carry
  PRESETS   (group, name, id, points), points = 9 lists of the 17 Morph* fields

Output: definitions for the declarations in SweetSpot.h (namespace UR44::Generated).

Usage: gen_sweet_spot_table.py SWEET_SPOT_PY OUTPUT_CPP
"""
import os
import runpy
import sys


def c_string(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append(f"\\{ord(ch):03o}")
    return '"' + "".join(out) + '"'


def main():
    source, output = sys.argv[1:3]
    data = runpy.run_path(source)
    notice = data["NOTICE"]
    presets = data["PRESETS"]
    for group, name, ident, points in presets:
        if len(points) != 9 or any(len(p) != 17 for p in points):
            sys.exit(f"{name}: expected 9 points of 17 values")
        if any(not 0 <= v <= 0xFFFF for p in points for v in p):
            sys.exit(f"{name}: value out of range")

    rel = os.path.relpath(source, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
    lines = [
        "// GENERATED FILE - DO NOT EDIT.",
        f"// Generated by gui/src/ur44/{os.path.basename(__file__)} from {rel}.",
        "// Change that (or the generator) instead; the build regenerates this file.",
        "//",
        "// The Sweet Spot Data presets come with Yamaha/Steinberg's TOOLS for UR44:",
        f"// {notice}",
        "",
        '#include "SweetSpot.h"',
        "",
        "#include <iterator>",
        "",
        "namespace UR44::Generated",
        "{",
        "",
        f"const char* const SWEET_SPOT_NOTICE = {c_string(notice)};",
        "",
        "const SweetSpotData SWEET_SPOT_PRESETS[] = {",
    ]
    for group, name, ident, points in presets:
        lines.append(f"    {{{c_string(group)}, {c_string(name)}, {c_string(ident)}, {{")
        for p in points:
            lines.append("        {" + ", ".join(str(v) for v in p) + "},")
        lines.append("    }},")
    lines += [
        "};",
        "",
        "const std::size_t SWEET_SPOT_PRESET_COUNT = std::size(SWEET_SPOT_PRESETS);",
        "",
        "}",
        "",
    ]
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    # Always written (even when unchanged), so the output is newer than its inputs and the build considers it done
    with open(output, "w") as f:
        f.write("\n".join(lines))
    print(f"{len(presets)} Sweet Spot presets -> {output}")


if __name__ == "__main__":
    main()
