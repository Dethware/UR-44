#!/usr/bin/env python3
"""Generate ParameterTable.cpp: the UR44 parameter table as constant C++ data (run by the build).

Inputs (both produced by the reverse engineering, see re/gen_params.py and re/dump_memapi_labels.py):
  tools/ur44_params.py      ids, names, ranges, defaults, instance counts, macOS name aliases
  tools/ur44_labels.json    display labels and units, as dspMixFx shows them

Output: definitions for the declarations in Parameters.h (namespace UR44::Generated):
  PARAMETERS[id]   one Parameter per id; ids are contiguous from 0, so the array is indexed by id
  NAME_INDEX       (name, id) for every name and alias, sorted by name for binary search
Label tables are shared between parameters with identical labels.

Usage: gen_parameter_table.py PARAMS_PY LABELS_JSON OUTPUT_CPP
"""
import json
import os
import runpy
import sys


def c_string(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append(f"\\{ord(ch):03o}")
    return '"' + "".join(out) + '"'


def main():
    params_py, labels_json, output = sys.argv[1:4]
    params = runpy.run_path(params_py)
    table = params["PARAMS"]
    aliases = params["ALIASES"]
    labels = json.load(open(labels_json))

    ids = [row[0] for row in table]
    if ids != list(range(len(ids))):
        sys.exit("parameter ids must be contiguous from 0")

    label_tables = {}  # tuple(labels) -> C name
    entries = []
    for pid, name, _group, lo, hi, default, instances in table:
        lab = labels[str(pid)]
        if (lab["min"], lab["max"]) != (lo, hi):
            sys.exit(f"{name}: label range {lab['min']}..{lab['max']} doesn't match {lo}..{hi}")
        values = lab["labels"]
        ref = "nullptr"
        if values:
            if len(values) != hi - lo + 1:
                sys.exit(f"{name}: {len(values)} labels for {hi - lo + 1} values")
            ref = label_tables.setdefault(tuple(values), f"LABELS_{len(label_tables)}")
        entries.append((pid, name, lo, hi, default, instances, lab["unit"], ref))

    names = [(name, pid) for pid, name, *_ in table]
    by_name = {n: p for n, p in names}
    for alias, target in aliases.items():
        names.append((alias, by_name[target]))
    names.sort()

    rel = lambda p: os.path.relpath(p, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
    lines = [
        "// GENERATED FILE - DO NOT EDIT.",
        f"// Generated by gui/src/ur44/{os.path.basename(__file__)} from {rel(params_py)} and {rel(labels_json)}.",
        "// Change those (or the generator) instead; the build regenerates this file.",
        "",
        '#include "Parameters.h"',
        "",
        "#include <iterator>",
        "",
        "namespace UR44::Generated",
        "{",
        "",
        "namespace",
        "{",
    ]
    for values, cname in label_tables.items():
        lines.append(f"constexpr const char* {cname}[] = {{")
        row = "   "
        for v in values:
            item = f" {c_string(v)},"
            if len(row) + len(item) > 118:
                lines.append(row)
                row = "   "
            row += item
        lines.append(row)
        lines.append("};")
    lines += [
        "}",
        "",
        "const Parameter PARAMETERS[] = {",
        "    // id, name, min, max, default, instances, unit, labels",
    ]
    for pid, name, lo, hi, default, instances, unit, ref in entries:
        lines.append(f"    {{{pid}, {c_string(name)}, {lo}, {hi}, {default}, {instances}, {c_string(unit)}, {ref}}},")
    lines += [
        "};",
        "",
        "const NameIndexEntry NAME_INDEX[] = {",
    ]
    for name, pid in names:
        lines.append(f"    {{{c_string(name)}, {pid}}},")
    lines += [
        "};",
        "",
        "const std::size_t PARAMETER_COUNT = std::size(PARAMETERS);",
        "const std::size_t NAME_INDEX_COUNT = std::size(NAME_INDEX);",
        "",
        "}",
        "",
    ]
    text = "\n".join(lines)
    os.makedirs(os.path.dirname(os.path.abspath(output)), exist_ok=True)
    # Always written (even when unchanged), so the output is newer than its inputs and the build considers it done
    with open(output, "w") as f:
        f.write(text)
    print(f"{len(entries)} parameters, {len(label_tables)} label tables, {len(names)} names -> {output}")


if __name__ == "__main__":
    main()
