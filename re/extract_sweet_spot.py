#!/usr/bin/env python3
"""Put the Sweet Spot Data presets (.ssd) from TOOLS for UR44 into a folder with their proper names.

The Windows installer's cab mangles the names (_2_color.ssd); each file carries its id ("0002"), which maps to
the name and group the presets have in the macOS package (TOOLS V2.3.0, ssmdPresets.pkg):
  <out>/Yamaha Preset/02 Color.ssd, <out>/Engineers' Preset/14 OK Master - Vocal.ssd, ...

Usage: extract_sweet_spot.py SOURCE_DIR OUT_DIR   (SOURCE_DIR: any folder with .ssd files, searched recursively)
       extract_sweet_spot.py --module SOURCE_DIR OUT.py
           writes the presets as a Python data module (tools/ur44_sweet_spot.py), from which the GUI build
           generates its built-in preset table
"""
import glob
import os
import shutil
import sys

YAMAHA = ["Basic", "Color", "Tone", "Sweep - Boost", "Sweep - Cut", "Lo Cut"]
ENGINEERS = ["AK Bass", "AK Drums", "AK Master", "MZ A.Guitar", "MZ Kick", "MZ Snare", "MZ Master", "MR Vocal",
             "MR Drums", "MR Master", "SH Piano", "SH Drums", "SH Master", "OK Master - Vocal", "OK Master - Bass",
             "OK Master - Vigour", "OK Master - TV", "IO Vocal", "IO A.Guitar", "IO Drums", "TK Notch - Resonation",
             "TK Programmed Kick", "TK Pumping", "ZK Vocal", "ZK Bass", "ZK Drums", "ZK Master", "ZK Filter"]
NAMES = {}
for i, n in enumerate(YAMAHA):
    NAMES[f"{i + 1:04d}"] = ("Yamaha Preset", f"{i + 1:02d} {n}")
for i, n in enumerate(ENGINEERS):
    NAMES[f"{len(YAMAHA) + i + 1:04d}"] = ("Engineers' Preset", f"{i + 1:02d} {n}")

def read_points(data):
    import struct
    return [list(struct.unpack_from(">20H", data, 0x20 + 40 * p)[:17]) for p in range(9)]


if sys.argv[1] == "--module":
    source, out = sys.argv[2], sys.argv[3]
    presets = {}
    for path in sorted(glob.glob(os.path.join(source, "**", "*.ssd"), recursive=True)):
        data = open(path, "rb").read()
        if not data.startswith(b"SSMD"):
            continue
        ident = data[16:32].split(b"\0")[0].decode("latin1")
        if ident in NAMES:
            notice = data[0x188:].split(b"\0")[0].decode("latin1")
            presets[ident] = (*NAMES[ident], ident, read_points(data), notice)
    if len(presets) != len(NAMES):
        sys.exit(f"found {len(presets)} of the {len(NAMES)} presets")
    notices = sorted({p[4] for p in presets.values()})
    with open(out, "w") as f:
        f.write('"""Sweet Spot Data presets of the UR44\'s Sweet Spot Morphing Channel Strip.\n\n'
                "GENERATED by re/extract_sweet_spot.py from the .ssd files in TOOLS for UR44 (do not edit).\n"
                "The preset data: " + "; ".join(notices) + "\n\n"
                "NOTICE: the copyright notice the .ssd files carry (keep it with the data)\n"
                "PRESETS: (group, name, id, points), points = 9 lists of the 17 Morph* fields in parameter order\n"
                '"""\n\n')
        f.write(f"NOTICE = {' / '.join(notices)!r}\n\nPRESETS = [\n")
        for ident in sorted(presets):
            group, name, ident, points, _ = presets[ident]
            f.write(f"    ({group!r}, {name!r}, {ident!r}, [\n")
            for p in points:
                f.write(f"        {p},\n")
            f.write("    ]),\n")
        f.write("]\n")
    print(f"{len(presets)} presets -> {out}")
    sys.exit(0)

source, out = sys.argv[1], sys.argv[2]
count = 0
for path in sorted(glob.glob(os.path.join(source, "**", "*.ssd"), recursive=True)):
    data = open(path, "rb").read()
    if not data.startswith(b"SSMD"):
        continue
    ident = data[16:32].split(b"\0")[0].decode("latin1")
    group, name = NAMES.get(ident, ("Other", os.path.splitext(os.path.basename(path))[0]))
    os.makedirs(os.path.join(out, group), exist_ok=True)
    shutil.copyfile(path, os.path.join(out, group, name + ".ssd"))
    count += 1
print(f"{count} Sweet Spot presets -> {out}")
