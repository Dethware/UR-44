#!/usr/bin/env python3
"""Generate the UR44 parameter table from memapi_ur44.dll (32-bit, MemAPI UR44 V2.1.0).

memapi holds 177 parameter descriptors at PTR_DAT_10022118[id], 0x2c bytes each:
  +0x00 u16 id, u16 0xffff   +0x04 type    +0x08 instance kind   +0x0c ?
  +0x10 0x38                 +0x14 group mask
  +0x18 max  +0x1c min  +0x20 default (dspMixFx's reset value, not device state)
  +0x24 storage ptr          +0x28 name (char *)
The wire parameter id == descriptor index. Instance counts are not in the descriptor in an
obvious form; they come from a live read sweep (docs/data/scan2d.txt) and the "All" bulk dump's
format chunk (tools/ur44_dump.py), and are encoded below.

Usage: gen_params.py memapi_ur44.dll  -> writes docs/data/memapi_param_table.txt, tools/ur44_params.py
"""
import os
import struct
import sys

BASE = 0x10000000
DESC_TABLE = 0x10022118
N = 0xB1
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

data = open(sys.argv[1], "rb").read()
u32 = lambda va: struct.unpack_from("<I", data, va - BASE)[0]


def cstr(va):
    o = va - BASE
    return data[o:data.index(b"\0", o)].decode("latin1")


def instances(pid, name):
    """Number of valid instance indices, from the live sweep."""
    if name.startswith("Ch"):
        return 6          # analog inputs 1..6
    if name.startswith("Ha"):
        return 3          # input pairs 1/2, 3/4, 5/6
    if name.startswith("Fx") and not name.startswith("FxRev"):
        return 4          # channel strip DSP slots
    if 0x53 <= pid <= 0x63:
        return 36         # morphing table: 4 channel strips x 9 points (bulk dump format chunk)
    if name.startswith("MorphSystem"):
        return 4
    return 1


rows = []
for pid in range(N):
    p = u32(DESC_TABLE + 4 * pid)
    w = struct.unpack_from("<11i", data, p - BASE)
    name = cstr(w[10] & 0xFFFFFFFF)
    rows.append(dict(id=pid, name=name, group=w[5] & 0xFFFFFFFF, type=w[1] & 0xFFFF, min=w[7], max=w[6],
                     default=w[8], kind=w[2], unk=w[3], n=instances(pid, name)))

with open(os.path.join(ROOT, "docs/data/memapi_param_table.txt"), "w") as f:
    f.write("id   name                             grp      type  min   max   def  kind unk  instances\n")
    for r in rows:
        f.write(f"0x{r['id']:02x} {r['name']:32s} {r['group']:08x} {r['type']:04x} {r['min']:5d} {r['max']:5d} "
                f"{r['default']:5d}  x{r['kind']}  {r['unk']:3d}  {r['n']}\n")

with open(os.path.join(ROOT, "tools/ur44_params.py"), "w") as f:
    f.write('"""UR44 parameter table, generated by re/gen_params.py from memapi_ur44.dll.\n\n'
            'Fields: id, name, group mask, min, max, default, instance count (from live index sweep).\n"""\n\n'
            "PARAMS = [\n")
    for r in rows:
        f.write(f"    (0x{r['id']:02x}, {r['name']!r}, 0x{r['group']:05x}, {r['min']}, {r['max']}, "
                f"{r['default']}, {r['n']}),\n")
    f.write("]\n\n# Names used by macOS MemAPI 2.3.0 where they differ from Windows memapi 2.1.0 (same ids)\n"
            "ALIASES = {'FxRevMixBus1Level': 'FxRevBus1Level', 'FxRevMixBus2Level': 'FxRevBus2Level',\n"
            "           'GtrFxCrunchHidMaxOut': 'GtrFxnCrunchHidMaxOut'}\n\n"
            "BY_NAME = {p[1]: p for p in PARAMS}\nBY_NAME.update({a: BY_NAME[n] for a, n in ALIASES.items()})\n"
            "BY_ID = {p[0]: p for p in PARAMS}\n")
print(f"{len(rows)} parameters")
